#!/usr/bin/env python3
"""Render clusters/re8ch/dissosy-resources.yaml from runner.py.

The CronJobs ship suspended. Unsuspend a persona only after its Secret exists:
  dissosy-<persona>-litellm : LITELLM_API_KEY (per-persona LiteLLM virtual key, created out of band
                              by Neo with a small weekly budget; see docs/MODEL-GATEWAY-AGENT-KEYS.md, #227)
  dissosy-github            : GITHUB_TOKEN for the persona's GitAccount bot (issues read/write on the
                              state repo only)
"""
import argparse
from pathlib import Path
import yaml

class _Dumper(yaml.SafeDumper):
    pass


def _str(dumper, value):
    style = '|' if '\n' in value else None
    return dumper.represent_scalar('tag:yaml.org,2002:str', value, style=style)


_Dumper.add_representer(str, _str)

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'clusters/re8ch/dissosy-resources.yaml'
NAMESPACE = 'ai-operations'
IMAGE = 'docker.1ms.run/library/python@sha256:d09d15e60962ca365d1cd544a48773bac9d33f2fb1b00f2aa0deec78ade7dc31'
# persona -> cron (Africa/Maputo). Ops Analyst first: read-only, lowest risk.
PERSONAS = {'ops-analyst': '22 7 * * 1-5'}


def cronjob(persona, schedule):
    name = f'dissosy-{persona}'
    return {
        'apiVersion': 'batch/v1', 'kind': 'CronJob',
        'metadata': {'name': name, 'namespace': NAMESPACE,
                     'labels': {'app.kubernetes.io/name': name, 'app.kubernetes.io/part-of': 'dissosy'}},
        'spec': {
            'schedule': schedule, 'timeZone': 'Africa/Maputo', 'suspend': True,
            'startingDeadlineSeconds': 3600, 'concurrencyPolicy': 'Forbid',
            'successfulJobsHistoryLimit': 3, 'failedJobsHistoryLimit': 3,
            'jobTemplate': {'spec': {
                'backoffLimit': 1, 'activeDeadlineSeconds': 1800, 'ttlSecondsAfterFinished': 604800,
                'template': {
                    'metadata': {'labels': {'app.kubernetes.io/name': name, 'app.kubernetes.io/part-of': 'dissosy'}},
                    'spec': {
                        'serviceAccountName': 'dissosy', 'automountServiceAccountToken': False,
                        'restartPolicy': 'Never',
                        'nodeSelector': {'kubernetes.io/hostname': 'overseas-flk'},
                        'tolerations': [
                            {'effect': 'NoSchedule', 'key': 'dedicated', 'operator': 'Equal', 'value': 'overseas-edge'},
                            {'effect': 'NoSchedule', 'key': 'scheduling.re8ch.com/capacity-window', 'operator': 'Equal', 'value': 'closed'},
                        ],
                        'securityContext': {'runAsNonRoot': True, 'runAsUser': 65532, 'runAsGroup': 65532,
                                            'seccompProfile': {'type': 'RuntimeDefault'}},
                        'containers': [{
                            'name': 'persona', 'image': IMAGE,
                            'command': ['python3', '/app/runner.py'],
                            'env': [
                                {'name': 'DISSOSY_PERSONA', 'value': persona},
                                {'name': 'LITELLM_BASE_URL', 'value': 'http://litellm.llm-gateway.svc.cluster.local:4000/v1'},
                                {'name': 'LITELLM_MODEL', 'value': 'deepseek-v4-flash'},
                                {'name': 'LITELLM_API_KEY', 'valueFrom': {'secretKeyRef': {'name': f'{name}-litellm', 'key': 'LITELLM_API_KEY'}}},
                                {'name': 'GITHUB_TOKEN', 'valueFrom': {'secretKeyRef': {'name': 'dissosy-github', 'key': 'GITHUB_TOKEN'}}},
                            ],
                            'resources': {'requests': {'cpu': '10m', 'memory': '32Mi'}, 'limits': {'cpu': '200m', 'memory': '128Mi'}},
                            'securityContext': {'allowPrivilegeEscalation': False, 'readOnlyRootFilesystem': True,
                                                'capabilities': {'drop': ['ALL']}},
                            'volumeMounts': [{'name': 'app', 'mountPath': '/app', 'readOnly': True}],
                        }],
                        'volumes': [{'name': 'app', 'configMap': {'name': 'dissosy-runner'}}],
                    },
                },
            }},
        },
    }


def render():
    runner = (ROOT / 'operations/dissosy/runner.py').read_text()
    docs = [
        {'apiVersion': 'v1', 'kind': 'ServiceAccount',
         'metadata': {'name': 'dissosy', 'namespace': NAMESPACE, 'labels': {'app.kubernetes.io/part-of': 'dissosy'}},
         'automountServiceAccountToken': False},
        {'apiVersion': 'v1', 'kind': 'ConfigMap',
         'metadata': {'name': 'dissosy-runner', 'namespace': NAMESPACE, 'labels': {'app.kubernetes.io/part-of': 'dissosy'}},
         'data': {'runner.py': runner}},
    ] + [cronjob(p, s) for p, s in PERSONAS.items()]
    header = '# Generated by operations/dissosy/render.py. Do not edit by hand.\n'
    return header + yaml.dump_all(docs, Dumper=_Dumper, sort_keys=False, width=1000, allow_unicode=True)


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    text = render()
    if a.check:
        if OUT.read_text() != text:
            raise SystemExit(f'{OUT} is stale; run operations/dissosy/render.py')
        print('dissosy manifests up to date')
    else:
        OUT.write_text(text)
        print(f'wrote {OUT}')
